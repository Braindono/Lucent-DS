#!/usr/bin/env python3
"""
Lucent token pipeline.

project/tokens.json is the single source of truth for every design token.
Everything under export/ (tokens.light.json, tokens.dark.json, typography.json,
motion.json, tokens.css) is GENERATED by this script. Do not hand-edit anything
under export/ -- change project/tokens.json and re-run this script instead:

    python3 project/scripts/regen_tokens.py

Re-run after any change to project/tokens.json. This script is idempotent:
running it twice with no source change produces byte-identical output.
"""
import json, re, hashlib, datetime, pathlib, zipfile, sys

HERE = pathlib.Path(__file__).resolve()
ROOT = HERE.parents[2]          # .../Design_System
PROJECT = ROOT / "project"
EXPORT = ROOT / "export"
SRC = PROJECT / "tokens.json"

ALIAS_RE = re.compile(r"\{([a-zA-Z0-9_-]+)\}")


def load_source():
    with open(SRC, encoding="utf-8") as f:
        return json.load(f)


# ---------------------------------------------------------------- color ----

def color_group_leaf(name):
    """Map a flat Lucent color token name to its (group, leaf) DTCG path.
    group is None for tokens that sit directly under `color`."""
    if name.startswith("ink-"):
        return "neutral", name[len("ink-"):]
    if name == "ink":
        return "text", "primary"
    if name == "ink-muted":
        return "text", "muted"
    if name == "ink-faint":
        return "text", "faint"
    if name.startswith("indigo-"):
        return "indigo", name[len("indigo-"):]
    if name.startswith("cyan-"):
        return "cyan", name[len("cyan-"):]
    if name.startswith("violet-"):
        return "violet", name[len("violet-"):]
    if name.startswith("surface-"):
        return "surface", name[len("surface-"):]
    if name.startswith("glass-"):
        return "glass", name[len("glass-"):]
    if name == "scrim":
        return None, "scrim"
    if name.startswith("accent-"):
        return "accent", name[len("accent-"):]
    if name == "focus-ring":
        return None, "focus-ring"
    if name.startswith("viz-series-"):
        return "viz", "series-" + name[len("viz-series-"):]
    if name.startswith("status-"):
        return "status", name[len("status-"):]
    raise ValueError(f"no color grouping rule for token {name!r} -- add one in regen_tokens.py")


def build_color_path_map(color_tokens):
    m = {}
    for tok in color_tokens:
        group, leaf = color_group_leaf(tok["name"])
        m[tok["name"]] = f"color.{group}.{leaf}" if group else f"color.{leaf}"
    return m


def resolve_alias(raw, path_map):
    """'{surface-base}' -> '{color.surface.base}'; a literal value passes through."""
    m = ALIAS_RE.fullmatch(raw.strip()) if isinstance(raw, str) else None
    if not m:
        return raw
    src_name = m.group(1)
    if src_name not in path_map:
        raise ValueError(f"alias {{{src_name}}} does not resolve to a known token")
    return "{" + path_map[src_name] + "}"


def build_color_tree(color_tokens, theme, path_map):
    tree = {}
    for tok in color_tokens:
        group, leaf = color_group_leaf(tok["name"])
        value = resolve_alias(tok["value"][theme], path_map)
        entry = {
            "$type": "color",
            "$value": value,
            "$description": tok["usage"],
            "$extensions": {"lucent.sourceName": tok["name"]},
        }
        if group:
            tree.setdefault(group, {})[leaf] = entry
        else:
            tree[leaf] = entry
    return tree


# --------------------------------------------------------------- shadow ----

# Supported shadow-string shape ONLY: "[inset ]<x>[px] <y>[px] <blur>px rgba?(...)"
# layers joined by "), " (as CSS box-shadow multi-layer values naturally render).
# No support for: em/%/other units, hex/named/hsl colors, or a spread value in the
# source string (spread is always written out as 0px). A token that needs any of
# those will raise ValueError here -- extend this regex deliberately, don't relax
# it silently, since tokens.css and the *.json exports must stay in lockstep.
SHADOW_LAYER_RE = re.compile(
    r"^(?P<inset>inset\s+)?"
    r"(?P<x>-?\d+(?:px)?)\s+(?P<y>-?\d+(?:px)?)\s+(?P<blur>\d+px)\s+"
    r"(?P<color>rgba?\([^)]*\))$"
)

def _px(v):
    return v if v.endswith("px") else v + "px"


def normalize_rgba(color):
    inner = color[color.index("(") + 1: color.rindex(")")]
    parts = [p.strip() for p in inner.split(",")]
    fn = color[: color.index("(")]
    return f"{fn}({', '.join(parts)})"


def parse_shadow(raw):
    layers = []
    for raw_layer in [s.strip() for s in raw.split("), ")]:
        if not raw_layer.endswith(")"):
            raw_layer += ")"
        m = SHADOW_LAYER_RE.match(raw_layer)
        if not m:
            raise ValueError(f"could not parse shadow layer: {raw_layer!r}")
        layers.append({
            "color": normalize_rgba(m.group("color")),
            "offsetX": _px(m.group("x")),
            "offsetY": _px(m.group("y")),
            "blur": m.group("blur"),
            "spread": "0px",
            "inset": bool(m.group("inset")),
        })
    return layers


def build_shadow_tree(shadow_tokens, theme):
    tree = {}
    for tok in shadow_tokens:
        tree[tok["name"]] = {
            "$type": "shadow",
            "$value": parse_shadow(tok["value"][theme]),
            "$description": tok["usage"],
            "$extensions": {"lucent.sourceName": tok["name"]},
        }
    return tree


# ------------------------------------------------- flat dimension/number ----

def build_flat_tree(tokens, kind):
    tree = {}
    for tok in tokens:
        value = tok["value"]
        if kind == "number":
            value = float(value)
        tree[tok["name"]] = {
            "$type": kind,
            "$value": value,
            "$description": tok["usage"],
            "$extensions": {"lucent.sourceName": tok["name"]},
        }
    return tree


# ------------------------------------------------------------ typography ----

def build_typography(type_data):
    fams = type_data["families"]
    font = {
        "sans": {"$type": "fontFamily", "$value": [p.strip().strip('"') for p in fams["sans"].split(",")]},
        "mono": {"$type": "fontFamily", "$value": [p.strip().strip('"') for p in fams["mono"].split(",")]},
    }
    typography = {}
    for group in type_data["groups"]:
        if group["name"] not in ("Display", "Heading", "Text", "Label"):
            continue  # foundations export only -- case-study-scoped groups stay out
        key = group["name"].lower()
        family_ref = "{font.mono}" if group.get("family") == "mono" else "{font.sans}"
        styles = {}
        for style in group["styles"]:
            value = {
                "fontFamily": family_ref,
                "fontSize": style["fontSize"],
                "fontWeight": style["fontWeight"],
                "lineHeight": style["lineHeight"],
            }
            if "letterSpacing" in style:
                value["letterSpacing"] = style["letterSpacing"]
            styles[style["name"]] = {
                "$type": "typography",
                "$value": value,
                "$description": style["usage"],
            }
        typography[key] = styles
    return {"font": font, "typography": typography}


# ----------------------------------------------------------------- motion --

def build_motion(motion_data):
    # DTCG has no keyframe/animation $type -- tokens that aren't a plain duration or
    # cubicBezier (e.g. status-pulse) are real, but they live in tokens.css only, not
    # in this spec-typed export. Skipping them here (rather than mistyping them as
    # $type "other") keeps motion.json something a strict DTCG consumer can trust.
    out = {}
    skipped = []
    for tok in motion_data["tokens"]:
        name = tok["name"]
        if name == "ease-out":
            nums = [float(x) for x in re.findall(r"-?\d*\.?\d+", tok["value"])]
            out[name] = {"$type": "cubicBezier", "$value": nums, "$description": tok["usage"]}
        elif name.startswith("dur-"):
            out[name] = {"$type": "duration", "$value": tok["value"], "$description": tok["usage"]}
        else:
            skipped.append(name)
    result = {"motion": out, "rules": motion_data["rules"]}
    if skipped:
        result["_notInDtcgExport"] = {
            "names": skipped,
            "why": "No DTCG $type covers a keyframe animation. See tokens.css for the actual @keyframes rule(s).",
        }
    return result


# --------------------------------------------------------------- tokens.css

def css_color_value(raw, theme_literals_ok=True):
    m = ALIAS_RE.fullmatch(raw.strip()) if isinstance(raw, str) else None
    if m:
        return f"var(--{m.group(1)})"
    return raw


def build_css(data, generated_at, src_hash):
    lines = []
    lines.append(f"/* GENERATED FILE -- do not hand-edit. */")
    lines.append(f"/* Source: project/tokens.json (sha256 {src_hash[:12]}...) */")
    lines.append(f"/* Generated: {generated_at} by project/scripts/regen_tokens.py */")
    lines.append(f"/* Re-run that script after changing project/tokens.json. */")
    lines.append("")

    for theme, selector in (("light", ':root, [data-theme="light"]'), ("dark", '[data-theme="dark"]')):
        lines.append(f"{selector} {{")
        for tok in data["color"]["tokens"]:
            lines.append(f"  --{tok['name']}: {css_color_value(tok['value'][theme])};")
        for tok in data["shadow"]["tokens"]:
            lines.append(f"  --{tok['name']}: {tok['value'][theme]};")
        lines.append("}")
        lines.append("")

    lines.append(":root {")
    for tok in data["spacing"]["tokens"]:
        lines.append(f"  --{tok['name']}: {tok['value']};")
    for tok in data["radius"]["tokens"]:
        lines.append(f"  --{tok['name']}: {tok['value']};")
    for tok in data["blur"]["tokens"]:
        lines.append(f"  --{tok['name']}: {tok['value']};")
    for tok in data["opacity"]["tokens"]:
        lines.append(f"  --{tok['name']}: {tok['value']};")
    if "textScale" in data["type"]:
        lines.append(f"  --text-scale: {data['type']['textScale']['value']};")
    lines.append(f"  --font-sans: {data['type']['families']['sans']};")
    lines.append(f"  --font-mono: {data['type']['families']['mono']};")
    for tok in data["motion"]["tokens"]:
        if tok["name"] in ("dur-fast", "dur-base", "ease-out"):
            lines.append(f"  --{tok['name']}: {tok['value']};")
    lines.append("}")
    lines.append("")

    lines.append("@keyframes status-pulse {")
    lines.append("  0%, 100% { opacity: 1; }")
    lines.append("  50% { opacity: .35; }")
    lines.append("}")
    lines.append("")
    lines.append("@media (prefers-reduced-motion: reduce) {")
    lines.append("  :root { --dur-fast: 0ms; --dur-base: 0ms; }")
    lines.append("  * { animation-duration: 0.001ms !important; animation-iteration-count: 1 !important; }")
    lines.append("}")
    lines.append("")

    for group in data["type"]["groups"]:
        if group["name"] not in ("Display", "Heading", "Text", "Label"):
            continue
        family_var = "var(--font-mono)" if group.get("family") == "mono" else "var(--font-sans)"
        for style in group["styles"]:
            lines.append(f".{style['name']} {{")
            lines.append(f"  font-family: {family_var};")
            lines.append(f"  font-size: {style['fontSize']};")
            lines.append(f"  line-height: {style['lineHeight']};")
            lines.append(f"  font-weight: {style['fontWeight']};")
            if "letterSpacing" in style:
                lines.append(f"  letter-spacing: {style['letterSpacing']};")
            lines.append("  margin: 0;")
            lines.append("}")
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------- main

def check_stale():
    """Exit 1 (with a message) if export/tokens.css's recorded source hash doesn't
    match project/tokens.json's current hash -- i.e. someone edited the source and
    never re-ran this script. Exit 0 (silent) if everything is in sync."""
    css_path = EXPORT / "tokens.css"
    if not css_path.exists():
        print("export/tokens.css does not exist yet -- run without --check to generate it.")
        return 1
    recorded = None
    for line in css_path.read_text(encoding="utf-8").splitlines()[:5]:
        m = re.search(r"sha256 ([0-9a-f]{12})", line)
        if m:
            recorded = m.group(1)
            break
    if recorded is None:
        print("export/tokens.css has no recorded source hash -- it predates --check. Re-run without --check.")
        return 1
    current = hashlib.sha256(SRC.read_bytes()).hexdigest()[:12]
    if recorded != current:
        print(f"STALE: export/ was generated from tokens.json hash {recorded}..., "
              f"but tokens.json is now {current}... . Run:\n\n"
              f"    python3 project/scripts/regen_tokens.py\n")
        return 1
    print("export/ is in sync with project/tokens.json.")
    return 0


def main():
    if "--check" in sys.argv:
        sys.exit(check_stale())
    data = load_source()
    src_bytes = SRC.read_bytes()
    src_hash = hashlib.sha256(src_bytes).hexdigest()
    generated_at = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    path_map = build_color_path_map(data["color"]["tokens"])

    for theme in ("light", "dark"):
        tree = {
            "color": build_color_tree(data["color"]["tokens"], theme, path_map),
            "shadow": build_shadow_tree(data["shadow"]["tokens"], theme),
            "spacing": build_flat_tree(data["spacing"]["tokens"], "dimension"),
            "radius": build_flat_tree(data["radius"]["tokens"], "dimension"),
            "blur": build_flat_tree(data["blur"]["tokens"], "dimension"),
            "opacity": build_flat_tree(data["opacity"]["tokens"], "number"),
        }
        out = EXPORT / f"tokens.{theme}.json"
        out.write_text(json.dumps(tree, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")

    typo = build_typography(data["type"])
    (EXPORT / "typography.json").write_text(json.dumps(typo, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {(EXPORT / 'typography.json').relative_to(ROOT)}")

    motion = build_motion(data["motion"])
    (EXPORT / "motion.json").write_text(json.dumps(motion, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {(EXPORT / 'motion.json').relative_to(ROOT)}")

    css = build_css(data, generated_at, src_hash)
    (EXPORT / "tokens.css").write_text(css, encoding="utf-8")
    print(f"wrote {(EXPORT / 'tokens.css').relative_to(ROOT)}")

    zip_path = ROOT / "lucent-tokens-export.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for name in ("README.md", "tokens.css", "tokens.light.json", "tokens.dark.json", "typography.json", "motion.json"):
            z.write(EXPORT / name, arcname=name)
    print(f"wrote {zip_path.relative_to(ROOT)}")

    print(f"\nsource sha256: {src_hash}")
    print(f"generated at:  {generated_at}")


if __name__ == "__main__":
    main()
